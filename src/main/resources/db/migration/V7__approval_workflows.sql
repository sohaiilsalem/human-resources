-- Configurable approval workflows (workflow module) and configurable employee requests (request module).
-- Default workflows and request types are seeded per tenant by the application (sign-up, and a start-up backfill
-- for tenants that existed before this version), not here: see docs/WORKFLOWS.md.

-- ---------------------------------------------------------------- workflow definitions

create table approval_workflows
(
    id          bigint generated by default as identity primary key,
    tenant_id   bigint       not null references tenants (id),
    code        varchar(30)  not null,
    name_en     varchar(100) not null,
    name_ar     varchar(100) not null,
    description varchar(500),
    is_default  boolean      not null,
    active      boolean      not null,
    created_at  timestamptz  not null,
    created_by  bigint,
    updated_at  timestamptz  not null,
    updated_by  bigint,
    version     bigint       not null,
    unique (tenant_id, code),
    check (active or not is_default)
);
-- exactly one default per tenant is enforced by the service; at most one by the database
create unique index approval_workflows_default_uq on approval_workflows (tenant_id) where is_default;

-- Steps are owned by their workflow and replaced as a whole on update (JPA element collection).
-- Steps with the same stage run in parallel; stages run in ascending order.
create table approval_workflow_steps
(
    workflow_id        bigint       not null references approval_workflows (id) on delete cascade,
    position           integer      not null,
    stage              integer      not null check (stage between 1 and 20),
    name_en            varchar(100) not null,
    name_ar            varchar(100) not null,
    approver_type      varchar(20)  not null,
    manager_level      integer check (manager_level between 1 and 10),
    role_code          varchar(30),
    user_id            bigint references users (id),
    condition_field    varchar(40),
    condition_operator varchar(5),
    condition_value    numeric(14, 2),
    if_unresolved      varchar(20)  not null,
    fallback_role_code varchar(30),
    primary key (workflow_id, position)
);

-- ---------------------------------------------------------------- running approvals

-- One per approved subject (a leave request, an employee request, ...), identified by (subject_type, subject_id).
create table approval_instances
(
    id             bigint generated by default as identity primary key,
    tenant_id      bigint       not null references tenants (id),
    subject_type   varchar(20)  not null,
    subject_id     bigint       not null,
    employee_id    bigint       not null references employees (id),
    workflow_code  varchar(30)  not null,
    summary_en     varchar(300) not null,
    summary_ar     varchar(300) not null,
    status         varchar(20)  not null,
    current_stage  integer,
    requested_by   bigint       not null,
    completed_at   timestamptz,
    created_at     timestamptz  not null,
    created_by     bigint,
    updated_at     timestamptz  not null,
    updated_by     bigint,
    version        bigint       not null,
    unique (tenant_id, subject_type, subject_id),
    unique (tenant_id, id)
);
create index approval_instances_status_idx on approval_instances (tenant_id, status);

-- The workflow's steps copied at submission: later changes to the workflow never alter a request in flight.
-- Approvers are resolved when a step's stage becomes active.
create table approval_steps
(
    id                 bigint generated by default as identity primary key,
    tenant_id          bigint       not null references tenants (id),
    instance_id        bigint       not null,
    stage              integer      not null,
    position           integer      not null,
    name_en            varchar(100) not null,
    name_ar            varchar(100) not null,
    approver_type      varchar(20)  not null,
    manager_level      integer,
    role_code          varchar(30),
    user_id            bigint,
    if_unresolved      varchar(20)  not null,
    fallback_role_code varchar(30),
    status             varchar(20)  not null,
    assignee_user_id   bigint,
    assignee_role_code varchar(30),
    decided_by         bigint,
    decided_at         timestamptz,
    note               varchar(500),
    created_at         timestamptz  not null,
    created_by         bigint,
    updated_at         timestamptz  not null,
    updated_by         bigint,
    version            bigint       not null,
    foreign key (tenant_id, instance_id) references approval_instances (tenant_id, id),
    unique (instance_id, position)
);
create index approval_steps_inbox_idx on approval_steps (tenant_id, status, assignee_user_id, assignee_role_code);

-- Audit trail: one row per thing that happened, never changed or deleted (see the revoke below).
create table approval_actions
(
    id            bigint generated by default as identity primary key,
    tenant_id     bigint      not null references tenants (id),
    instance_id   bigint      not null,
    step_id       bigint references approval_steps (id),
    action        varchar(20) not null,
    actor_user_id bigint,
    note          varchar(500),
    created_at    timestamptz not null,
    created_by    bigint,
    updated_at    timestamptz not null,
    updated_by    bigint,
    version       bigint      not null,
    foreign key (tenant_id, instance_id) references approval_instances (tenant_id, id)
);
create index approval_actions_instance_idx on approval_actions (tenant_id, instance_id, id);

-- ---------------------------------------------------------------- configurable employee requests

create table request_types
(
    id              bigint generated by default as identity primary key,
    tenant_id       bigint       not null references tenants (id),
    code            varchar(30)  not null,
    name_en         varchar(100) not null,
    name_ar         varchar(100) not null,
    description_en  varchar(500),
    description_ar  varchar(500),
    category        varchar(20)  not null,
    fields          jsonb        not null,
    workflow_code   varchar(30),
    self_service    boolean      not null,
    allow_on_behalf boolean      not null,
    max_per_month   integer check (max_per_month > 0),
    active          boolean      not null,
    sort_order      integer      not null,
    created_at      timestamptz  not null,
    created_by      bigint,
    updated_at      timestamptz  not null,
    updated_by      bigint,
    version         bigint       not null,
    unique (tenant_id, code),
    unique (tenant_id, id)
);

create table employee_requests
(
    id              bigint generated by default as identity primary key,
    tenant_id       bigint        not null references tenants (id),
    request_type_id bigint        not null,
    employee_id     bigint        not null references employees (id),
    status          varchar(20)   not null,
    data            jsonb         not null,
    reason          varchar(1000),
    requested_by    bigint        not null,
    decided_at      timestamptz,
    decision_note   varchar(500),
    created_at      timestamptz   not null,
    created_by      bigint,
    updated_at      timestamptz   not null,
    updated_by      bigint,
    version         bigint        not null,
    foreign key (tenant_id, request_type_id) references request_types (tenant_id, id)
);
create index employee_requests_employee_idx on employee_requests (tenant_id, employee_id, created_at);
create index employee_requests_status_idx on employee_requests (tenant_id, status, created_at);

-- ---------------------------------------------------------------- leave types choose their workflow (null = default)

alter table leave_types add column workflow_code varchar(30);

-- ---------------------------------------------------------------- row-level security

do $$
    declare
        t text;
    begin
        foreach t in array array ['approval_workflows', 'approval_instances', 'approval_steps', 'approval_actions',
            'request_types', 'employee_requests']
            loop
                execute format('alter table %I enable row level security', t);
                execute format('alter table %I force row level security', t);
                execute format('create policy tenant_isolation on %I using (tenant_id = app_current_tenant())'
                                   || ' with check (tenant_id = app_current_tenant())', t);
            end loop;
    end
$$;

alter table approval_workflow_steps enable row level security;
alter table approval_workflow_steps force row level security;
create policy tenant_isolation on approval_workflow_steps
    using (exists (select 1 from approval_workflows w where w.id = workflow_id))
    with check (exists (select 1 from approval_workflows w where w.id = workflow_id));

-- The application may add to the audit trail but never rewrite it.
revoke update, delete, truncate on approval_actions from ${appRole};

-- ---------------------------------------------------------------- new permissions for existing HR administrators

insert into role_permissions (role_id, permission)
select r.id, p.permission
from roles r
         cross join (values ('request:manage'), ('workflow:manage')) as p(permission)
where r.code = 'HR_ADMIN'
on conflict do nothing;
