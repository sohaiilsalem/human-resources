-- Foundation: tenancy helpers, platform tables (no RLS), Modulith event outbox, plan catalogue.
-- Runs as the schema owner; the application connects as ${appRole}, which is subject to row-level security.

create function app_current_tenant() returns bigint
    language sql stable
as $$ select nullif(current_setting('app.tenant_id', true), '')::bigint $$;

grant usage on schema public to ${appRole};
alter default privileges in schema public grant select, insert, update, delete on tables to ${appRole};
-- Identity columns draw from sequences; the application role needs them to insert rows and to reserve tenant ids.
alter default privileges in schema public grant usage on sequences to ${appRole};

-- ---------------------------------------------------------------- platform
create table tenants
(
    id             bigint generated by default as identity primary key,
    slug           varchar(40)  not null unique,
    name           varchar(200) not null,
    status         varchar(20)  not null,
    time_zone      varchar(50)  not null,
    default_locale varchar(5)   not null,
    created_at     timestamptz  not null,
    created_by     bigint,
    updated_at     timestamptz  not null,
    updated_by     bigint,
    version        bigint       not null
);

-- ---------------------------------------------------------------- billing
create table plans
(
    id                         bigint generated by default as identity primary key,
    code                       varchar(30)    not null unique,
    name_en                    varchar(100)   not null,
    name_ar                    varchar(100)   not null,
    monthly_price_per_employee numeric(14, 2) not null,
    yearly_price_per_employee  numeric(14, 2) not null,
    max_employees              integer,
    max_branches               integer,
    active                     boolean        not null,
    sort_order                 integer        not null,
    created_at                 timestamptz    not null,
    created_by                 bigint,
    updated_at                 timestamptz    not null,
    updated_by                 bigint,
    version                    bigint         not null
);

create table plan_features
(
    plan_id bigint        not null references plans (id) on delete cascade,
    feature varchar(40) not null,
    primary key (plan_id, feature)
);

create table subscriptions
(
    id                   bigint generated by default as identity primary key,
    tenant_id            bigint        not null unique references tenants (id),
    plan_id              bigint        not null references plans (id),
    status               varchar(20) not null,
    billing_cycle        varchar(10) not null,
    seats                integer     not null,
    current_period_start timestamptz not null,
    current_period_end   timestamptz not null,
    trial_ends_at        timestamptz,
    created_at           timestamptz not null,
    created_by           bigint,
    updated_at           timestamptz not null,
    updated_by           bigint,
    version              bigint      not null
);

