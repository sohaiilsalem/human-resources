create table job_titles
(
    id         bigint generated by default as identity primary key,
    tenant_id  bigint       not null references tenants (id),
    code       varchar(30)  not null,
    name_en    varchar(100) not null,
    name_ar    varchar(100) not null,
    created_at timestamptz  not null,
    created_by bigint,
    updated_at timestamptz  not null,
    updated_by bigint,
    version    bigint       not null,
    unique (tenant_id, code),
    unique (tenant_id, id)
);

alter table employees add column job_title_id bigint;

alter table employees
    add constraint employee_job_title_tenant_fk
        foreign key (tenant_id, job_title_id) references job_titles (tenant_id, id);

create index employees_job_title_idx on employees (tenant_id, job_title_id);

alter table job_titles enable row level security;
alter table job_titles force row level security;
create policy tenant_isolation on job_titles
    using (tenant_id = app_current_tenant())
    with check (tenant_id = app_current_tenant());
