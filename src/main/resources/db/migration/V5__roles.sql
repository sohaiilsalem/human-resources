-- Roles become per-tenant data: each company gets the default roles at sign-up and can add its own.
-- Permissions stay in code (they guard endpoints); a role is a named set of them.

create table roles
(
    id         bigint generated by default as identity primary key,
    tenant_id  bigint       not null references tenants (id),
    code       varchar(30)  not null,
    name_en    varchar(100) not null,
    name_ar    varchar(100) not null,
    created_at timestamptz  not null,
    created_by bigint,
    updated_at timestamptz  not null,
    updated_by bigint,
    version    bigint       not null,
    unique (tenant_id, code)
);

-- No rows for OWNER: it always holds every permission, including ones added later.
create table role_permissions
(
    role_id    bigint      not null references roles (id) on delete cascade,
    permission varchar(40) not null,
    primary key (role_id, permission)
);

alter table roles enable row level security;
alter table roles force row level security;
create policy tenant_isolation on roles
    using (tenant_id = app_current_tenant())
    with check (tenant_id = app_current_tenant());

alter table role_permissions enable row level security;
alter table role_permissions force row level security;
create policy tenant_isolation on role_permissions
    using (exists (select 1 from roles r where r.id = role_id))
    with check (exists (select 1 from roles r where r.id = role_id));

-- ---------------------------------------------------------------- default roles for existing tenants
create temporary table default_roles (code varchar(30), name_en varchar(100), name_ar varchar(100), sort int);
insert into default_roles
values ('OWNER', 'Owner', 'المالك', 1),
       ('HR_ADMIN', 'HR administrator', 'مسؤول الموارد البشرية', 2),
       ('PAYROLL_ADMIN', 'Payroll administrator', 'مسؤول الرواتب', 3),
       ('MANAGER', 'Manager', 'مدير', 4),
       ('EMPLOYEE', 'Employee', 'موظف', 5);

insert into roles (tenant_id, code, name_en, name_ar, created_at, updated_at, version)
select t.id, d.code, d.name_en, d.name_ar, now(), now(), 0
from tenants t
         cross join default_roles d
order by t.id, d.sort;

insert into role_permissions (role_id, permission)
select r.id, p.permission
from roles r
         join (values ('HR_ADMIN', 'user:manage'), ('HR_ADMIN', 'organization:manage'),
                      ('HR_ADMIN', 'employee:read'), ('HR_ADMIN', 'employee:write'),
                      ('HR_ADMIN', 'attendance:manage'), ('HR_ADMIN', 'leave:manage'),
                      ('HR_ADMIN', 'leave:approve'), ('HR_ADMIN', 'self:service'),
                      ('PAYROLL_ADMIN', 'employee:read'), ('PAYROLL_ADMIN', 'payroll:read'),
                      ('PAYROLL_ADMIN', 'payroll:run'), ('PAYROLL_ADMIN', 'self:service'),
                      ('MANAGER', 'employee:read'), ('MANAGER', 'leave:approve'), ('MANAGER', 'self:service'),
                      ('EMPLOYEE', 'self:service')) as p(code, permission) on p.code = r.code;

drop table default_roles;

-- ---------------------------------------------------------------- user_roles: role name → roles.id
alter table user_roles add column role_id bigint references roles (id);

update user_roles ur
set role_id = r.id
from users u
         join roles r on r.tenant_id = u.tenant_id
where u.id = ur.user_id
  and r.code = ur.role;

alter table user_roles alter column role_id set not null;
alter table user_roles drop constraint user_roles_pkey;
alter table user_roles drop column role;
alter table user_roles add primary key (user_id, role_id);
create index user_roles_role_idx on user_roles (role_id);

-- A user may only hold roles of their own tenant (roles is itself filtered by tenant).
drop policy tenant_isolation on user_roles;
create policy tenant_isolation on user_roles
    using (exists (select 1 from users u where u.id = user_id))
    with check (exists (select 1 from users u where u.id = user_id) and
                exists (select 1 from roles r where r.id = role_id));
